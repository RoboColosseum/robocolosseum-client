"""Nine-file training delivery, after validation against device-local raw evidence.

This profile deliberately cannot reconstruct the original capture. Only business
records (complete model actions, inference/operator events, scores and setup) are
embedded in episode metadata. Physical signals are ordinary numeric features.
"""
from bisect import bisect_right
from pathlib import Path
import hashlib
import json
import shutil

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

from .roboeval_compact import (EPISODES, MARKER, check_inventory, digest, inventory,
                              probe, read_json, write_json)

PROFILE = 'yam-30hz-physical-v1'
SIDES = ('left', 'right')
# key -> raw feedback field, per-arm dimensions, units, coordinate names
SIGNALS = {
    'observation.joint_velocity': ('joint_velocity_rad_s', 6, 'rad/s', tuple(f'joint_{i}' for i in range(1, 7))),
    'observation.joint_torque': ('joint_torque_nm', 6, 'N.m', tuple(f'joint_{i}' for i in range(1, 7))),
    'observation.eef_position': ('eef_position_world_m', 3, 'm', ('x', 'y', 'z')),
    'observation.eef_orientation': ('eef_orientation_world_wxyz', 4, 'unit quaternion', ('w', 'x', 'y', 'z')),
    'observation.gripper_width': ('gripper_width_m', 1, 'm', ('gripper',)),
    'observation.gripper_reading': ('gripper_reading_normalized_unclipped', 1, 'normalized, unclipped', ('gripper',)),
}
COMMANDS = {'action.gripper_command': 'normalized', 'action.gripper_command_width': 'm'}


def names(key):
    axes = SIGNALS[key][3] if key in SIGNALS else ('gripper',)
    return [f'{side}_{axis}' for side in SIDES for axis in axes]


def physical_vectors(rows, states, actions):
    """Select feedback and SDK-accepted commands causally on the training grid."""
    result = {key: [] for key in (*SIGNALS, *COMMANDS)}
    feedback = {s: [r for r in states if r['arm_id'] == s] for s in SIDES}
    commands = {s: sorted((r for r in actions if r['kind'] == 'sent_command' and r['arm_id'] == s),
                          key=lambda r: r['command_monotonic_s']) for s in SIDES}
    feedback_times = {s: [r['feedback_received_monotonic_s'] for r in feedback[s]] for s in SIDES}
    command_times = {s: [r['command_monotonic_s'] for r in commands[s]] for s in SIDES}
    for row in rows:
        stamp = row['captured_monotonic_s']
        picked = {}
        sent = {}
        for side in SIDES:
            for streams, field, target, times in ((feedback, 'feedback_received_monotonic_s', picked, feedback_times),
                                            (commands, 'command_monotonic_s', sent, command_times)):
                sequence = streams[side]
                # Feedback ordering is validated by align before this function.
                index = bisect_right(times[side], stamp) - 1
                if index < 0:
                    raise ValueError(f'Missing causal {side} {field}')
                target[side] = sequence[index]
        for key, (field, size, _, _) in SIGNALS.items():
            value = []
            for side in SIDES:
                raw = picked[side].get(field)
                vector = np.asarray([raw] if size == 1 else raw, dtype=np.float32)
                if vector.shape != (size,) or not np.isfinite(vector).all():
                    raise ValueError(f'Missing or invalid physical feedback: {side} {field}')
                value.extend(vector.tolist())
            result[key].append(value)
        normalized, widths = [], []
        for side in SIDES:
            command = sent[side]
            values = np.asarray(command.get('values'), dtype=float)
            width = command.get('gripper_command_width_m')
            if values.shape != (7,) or not np.isfinite(values).all() or width is None or not np.isfinite(width):
                raise ValueError(f'Missing or invalid actual gripper command: {side}')
            normalized.append(values[6]); widths.append(width)
        result['action.gripper_command'].append(normalized)
        result['action.gripper_command_width'].append(widths)
    return {key: np.asarray(value, np.float32) for key, value in result.items()}


def make_delivery(source, destination):
    """Source is a fully validated expanded export generated by this invocation."""
    source, destination = Path(source), Path(destination)
    if destination.exists():
        raise FileExistsError(destination)
    _, marker = check_inventory(source)
    info = read_json(source / 'meta/info.json')
    if marker.get('delivery_profile') != PROFILE or info['fps'] != 30:
        raise ValueError('Wrong training delivery profile')
    files = {'data/chunk-000/file-000.parquet', 'meta/info.json', 'meta/stats.json', 'meta/tasks.parquet'}
    for key, feature in info['features'].items():
        if feature['dtype'] == 'video':
            files.add(info['video_path'].format(video_key=key, chunk_index=0, file_index=0))
    if len(files) != 7:
        raise ValueError('Training delivery requires exactly three cameras')
    destination.mkdir(parents=True)
    for name in files:
        output = destination / name
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / name, output)
    episode = pq.read_table(source / EPISODES)
    for stream in ('actions', 'shared'):
        table = pq.read_table(source / f'meta/roboeval/{stream}.parquet')
        episode = episode.append_column(f'roboeval/{stream}', pa.array([table.to_pylist()], type=pa.list_(pa.struct(table.schema))))
    resources = [dict(path=p.relative_to(source / 'meta/roboeval').as_posix(), content=p.read_bytes())
                 for p in sorted((source / 'meta/roboeval/models').rglob('*')) if p.is_file()]
    episode = episode.append_column('roboeval/model_resources', pa.array([resources], type=pa.list_(pa.struct([
        ('path', pa.string()), ('content', pa.binary())]))))
    (destination / EPISODES).parent.mkdir(parents=True)
    pq.write_table(episode, destination / EPISODES)
    # Setup, clocks and outcome carry calibration, identities and business timing.
    setup = read_json(source / 'meta/roboeval/setup.json')
    setup.pop('selected_fields', None)
    setup.pop('stream_semantics', None)
    clock = read_json(source / 'meta/roboeval/clock.json')
    for key in ('events_source_sha256', 'stream_timestamps', 'camera_time_semantics'):
        clock.pop(key, None)
    continuous = marker.pop('continuous_recording')
    for key in ('roboeval_source_sha256', 'roboeval_shared_source_sha256', 'capture_timestamp_semantics'):
        marker.pop(key, None)
    marker['training_layout'] = dict(profile=PROFILE, setup=setup, clock=clock,
        outcome=read_json(source / 'meta/roboeval/outcome.json'),
        grid_start_monotonic_s=continuous['start_monotonic_s'],
        grid_end_monotonic_s=continuous['end_monotonic_s'],
        feedback_alignment='latest feedback received at or before each 30 Hz timestamp; no interpolation',
        command_alignment='latest SDK-accepted command at or before each 30 Hz timestamp',
        action_semantics=continuous['action_semantics'],
        eef_frame='recorded setup world transform; see each arm base_to_world; calibration accuracy is not asserted',
        eef_source='forward kinematics from measured joint positions and the recorded robot model/setup',
        validation='raw capture checked before export; raw streams and per-sample tracing excluded from delivery',
        units={**{k: v[2] for k, v in SIGNALS.items()}, **COMMANDS},
        episode_records={'roboeval/actions': 'complete raw model blocks including unused tail and accepted commands',
                         'roboeval/shared': 'inference timing/status and lifecycle/operator/error events'})
    marker['roboeval_shared_source_sha256'] = hashlib.sha256(json.dumps(dict(
        clock=clock, rows=episode['roboeval/shared'][0].as_py(),
        outcome=marker['training_layout']['outcome']), sort_keys=True, allow_nan=False).encode()).hexdigest()
    marker['files'] = {name: entry['sha256'] for name, entry in inventory(destination).items()}
    write_json(destination / MARKER, marker)
    validate_delivery(destination)


def validate_delivery(root):
    """Validate delivered structure/values, not reconstruct removed raw streams."""
    root = Path(root)
    actual, marker = check_inventory(root)
    info = read_json(root / 'meta/info.json')
    layout = marker.get('training_layout', {})
    if len(actual) != 9 or marker.get('delivery_profile') != PROFILE or layout.get('profile') != PROFILE:
        raise ValueError('Invalid nine-file training layout')
    data = pq.read_table(root / 'data/chunk-000/file-000.parquet')
    episode_table = pq.read_table(root / EPISODES)
    if episode_table.num_rows != 1 or info['fps'] != 30 or info['total_episodes'] != 1 or data.num_rows != info['total_frames'] or not data.num_rows:
        raise ValueError('Invalid training dataset length/rate')
    ep = episode_table.to_pylist()[0]
    if any(k in ep for k in ('roboeval/states', 'roboeval/frames')) or 'continuous_recording' in marker or 'roboeval_layout' in marker:
        raise ValueError('Unexpected raw tracing in delivery')
    expected = {'observation.state', 'action', 'timestamp', 'frame_index', 'episode_index', 'index', 'task_index', *SIGNALS, *COMMANDS}
    if 'observation.gripper_effort_nm' in data.column_names:
        expected.add('observation.gripper_effort_nm')
    if set(data.column_names) != expected:
        raise ValueError('Unexpected/missing training physical features')
    stats = read_json(root / 'meta/stats.json')
    videos = {k for k, f in info['features'].items() if f['dtype'] == 'video'}
    if set(info['features']) != expected | videos or set(stats) != set(info['features']) or len(videos) != 3:
        raise ValueError('Feature/statistics inventory mismatch')
    from .lerobot_export import _stats
    for key in expected:
        values = np.asarray(data[key].to_pylist())
        feature = info['features'][key]
        dimension = 14 if key in ('action', 'observation.state') else (2 * SIGNALS[key][1] if key in SIGNALS else 2)
        if key in ('timestamp', 'frame_index', 'episode_index', 'index', 'task_index'):
            dimension = None
        if not np.isfinite(values).all() or (dimension and (values.shape != (data.num_rows, dimension) or feature['shape'] != [dimension])):
            raise ValueError(f'Invalid physical feature: {key}')
        for name, expected_value in _stats(values).items():
            if not np.allclose(stats[key][name], expected_value, rtol=1e-6, atol=1e-8) or ep.get(f'stats/{key}/{name}') != stats[key][name]:
                raise ValueError(f'Physical statistics differ: {key}')
    for key in ('index', 'frame_index'):
        if data[key].to_pylist() != list(range(data.num_rows)):
            raise ValueError('Noncontiguous frame indices')
    for key in ('episode_index', 'task_index'):
        if any(data[key].to_pylist()):
            raise ValueError('Invalid single-episode/task index')
    if not np.array_equal(np.asarray(data['timestamp']), np.arange(data.num_rows, dtype=np.float32) / 30):
        raise ValueError('Training timestamps are not 30 Hz')
    if ep['length'] != data.num_rows or ep['dataset_from_index'] != 0 or ep['dataset_to_index'] != data.num_rows:
        raise ValueError('Episode offsets differ')
    from .roboeval_shared import validate_shared
    validate_shared(root, marker, payload={'documents': {'clock': layout['clock'], 'outcome': layout['outcome']},
                                          'rows': ep['roboeval/shared']})
    kinds = {r['kind'] for r in ep['roboeval/actions']}
    if not {'raw_policy', 'sent_command'} <= kinds:
        raise ValueError('Missing complete action records')
    for key in videos:
        path = info['video_path'].format(video_key=key, chunk_index=0, file_index=0)
        streams = probe(root / path)['streams']
        if len(streams) != 1:
            raise ValueError('Unexpected source tracks in training video')
        s = streams[0]
        if (s['codec_type'], s['r_frame_rate'], int(s['nb_frames'])) != ('video', '30/1', data.num_rows):
            raise ValueError('Invalid training video rate/count')
        if info['features'][key]['shape'] != [s['height'], s['width'], 3]:
            raise ValueError('Video dimensions differ')
